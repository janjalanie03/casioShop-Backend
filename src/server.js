import express from 'express';
import cors from 'cors';import helmet from 'helmet';import { rateLimit } from 'express-rate-limit';
import { randomUUID } from 'node:crypto';
import { env } from './config/env.js';import api from './routes/api.js';import { errors } from './middleware/errors.js';
import swaggerUi from 'swagger-ui-express';import {readFileSync} from 'node:fs';
export const app=express();app.disable('x-powered-by');app.set('trust proxy',1);app.use(helmet());
app.use((req,res,next)=>{req.id=randomUUID();res.setHeader('X-Request-ID',req.id);next()});
app.use(cors({origin:(origin,cb)=>cb(null,!origin||env.corsOrigins.includes(origin))}));
app.use('/api/v1/auth',rateLimit({windowMs:15*60*1000,limit:50,standardHeaders:'draft-8',legacyHeaders:false}));
app.use(express.json({limit:'100kb'}));
app.use('/api/v1',api);
app.get('/',(req,res)=>res.json({service:'Casio Watch Store API',version:'v1',docs:'/api-docs'}));
app.use('/api-docs',swaggerUi.serve,swaggerUi.setup(JSON.parse(readFileSync(new URL('../openapi.json',import.meta.url),'utf8'))));
app.use((req,res)=>res.status(404).json({success:false,error:{code:'NOT_FOUND',message:'Endpoint not found'},requestId:req.id}));
app.use(errors);
if(process.env.NODE_ENV!=='test')app.listen(env.port,()=>console.log(`Casio API at http://localhost:${env.port}`));
